"""Extracts the messages of the engine into ``locales/probandia.pot``.

    python -m probandia.i18n.extract           # writes probandia.pot and updates en, fr
    python -m probandia.i18n.extract --check   # exit code 1 if they are out of date

Messages are the string literals passed to ``_()``, ``N_()`` and ``ngettext()``
in the package (the vendored libraries excepted). The English catalogue keeps
empty translations: English messages are their own ids.
"""
import ast
import functools
import os
import sys

from probandia.i18n import DOMAIN, quote_po, read_po, repo_locales_dir

PACKAGE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = ("_vendor", "__pycache__")

HEADER = """\
# Messages of Probandia.
# This file is generated by: python -m probandia.i18n.extract
msgid ""
msgstr ""
"Project-Id-Version: probandia\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"""


def _literal(node):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def module_messages(path):
    """[(msgid, msgid_plural or None)] of one module, in the order of the file."""
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read(), path)
    calls = [n for n in ast.walk(tree) if isinstance(n, ast.Call)
             and isinstance(n.func, ast.Name) and n.func.id in ("_", "N_", "ngettext")]
    out = []
    for call in sorted(calls, key=lambda c: (c.lineno, c.col_offset)):
        if not call.args:
            continue
        msgid = _literal(call.args[0])
        plural = _literal(call.args[1]) if call.func.id == "ngettext" and len(call.args) > 1 else None
        if msgid is not None:
            out.append((msgid, plural))
    return out


def messages(package_dir=PACKAGE_DIR):
    """[(msgid, msgid_plural or None, [locations])] in order of first appearance."""
    found = {}
    for folder, dirs, files in os.walk(package_dir):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(files):
            if not name.endswith(".py"):
                continue
            path = os.path.join(folder, name)
            rel = os.path.relpath(path, os.path.dirname(package_dir)).replace(os.sep, "/")
            for key in module_messages(path):
                locs = found.setdefault(key, [])
                if rel not in locs:  # files only: line numbers would churn the template
                    locs.append(rel)
    return [(k[0], k[1], locs) for k, locs in found.items()]


REPORT_LABELS = "probandia/report/labels.py"


@functools.lru_cache(maxsize=1)
def report_labels():
    """The msgids of the report's labels, the trees' legend among them (T70): all a report in another
    language needs translated, where the engine's whole catalogue holds about seven times as many."""
    return tuple(dict.fromkeys(m for m, plural in module_messages(
        os.path.join(os.path.dirname(PACKAGE_DIR), *REPORT_LABELS.split("/"))) if plural is None))


def render_pot(msgs):
    out = [HEADER]
    for msgid, plural, locs in msgs:
        out.append("")
        out.append("#: " + " ".join(locs))
        out.append("msgid " + quote_po(msgid))
        if plural is not None:
            out.append("msgid_plural " + quote_po(plural))
            out.append('msgstr[0] ""')
            out.append('msgstr[1] ""')
        else:
            out.append('msgstr ""')
    return "\n".join(out) + "\n"


def render_po(msgs, existing, lang):
    """A catalogue for ``lang``: the messages of the template, with the
    translations already in ``existing`` kept."""
    header = HEADER.replace('"Project-Id-Version: probandia\\n"',
                            f'"Project-Id-Version: probandia\\n"\n"Language: {lang}\\n"')
    out = [header]
    for msgid, plural, locs in msgs:
        out.append("")
        out.append("#: " + " ".join(locs))
        out.append("msgid " + quote_po(msgid))
        if plural is not None:
            forms = existing.get((msgid, plural)) or ["", ""]
            out.append("msgid_plural " + quote_po(plural))
            for i, form in enumerate(forms):
                out.append(f"msgstr[{i}] " + quote_po(form))
        else:
            out.append("msgstr " + quote_po(existing.get(msgid, "")))
    return "\n".join(out) + "\n"


def languages(locales_dir):
    """English, then every language that has a catalogue in ``locales_dir``."""
    found = ["en"]
    if os.path.isdir(locales_dir):
        for lang in sorted(os.listdir(locales_dir)):
            if lang != "en" and os.path.isfile(os.path.join(locales_dir, lang, "LC_MESSAGES", DOMAIN + ".po")):
                found.append(lang)
    return found


def targets(locales_dir=None):
    """{path: expected content} for the template and each catalogue: English,
    and the translations shipped with the engine (French), whose translations are kept."""
    locales_dir = locales_dir or repo_locales_dir()
    msgs = messages()
    out = {os.path.join(locales_dir, DOMAIN + ".pot"): render_pot(msgs)}
    for lang in languages(locales_dir):
        path = os.path.join(locales_dir, lang, "LC_MESSAGES", DOMAIN + ".po")
        existing = read_po(path) if os.path.isfile(path) else {}
        out[path] = render_po(msgs, existing, lang)
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    stale = []
    for path, content in targets().items():
        current = None
        if os.path.isfile(path):
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        if current != content:
            stale.append(path)
            if "--check" not in argv:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(content)
    for path in stale:
        print(("out of date: " if "--check" in argv else "wrote: ") + path)
    return 1 if stale and "--check" in argv else 0


if __name__ == "__main__":
    sys.exit(main())
