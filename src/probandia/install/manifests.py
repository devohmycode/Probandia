"""``manifests generate|check``: every harness's files, written from the Claude layout.

The Claude layout is the single source: ``.claude-plugin/plugin.json``,
``skills/``, ``commands/``, ``agents/`` and ``hooks/hooks.json``.
The generated files are committed, because installing from git needs them;
``check`` fails when one of them no longer matches its source.

The Claude Code plugin declares no MCP server (token-economy E1): its skills call
the engine through the shell, and the server's tool definitions cost every turn.
Claude Code loads any ``.mcp.json`` at the plugin root, so there is none; Cursor's
server is in ``cursor/mcp.json``, generated too.

| Harness | Files |
|---|---|
| Claude Code | ``.claude-plugin/agents/<role>.md``: ``agents/`` with each role's model and effort (``ROLE_DEFAULTS``); ``agents`` of ``.claude-plugin/plugin.json`` names them, in place of ``agents/``, which Antigravity reads |
| Codex | ``.codex-plugin/plugin.json``; ``hooks/codex.json``; the root ``plugin.json`` (Agent Plugins 1.0, with an ``extensions.com.openai`` block); ``mcp.json`` with ``${PLUGIN_ROOT}``; ``.agents/plugins/marketplace.json`` |
| Cursor | ``.cursor-plugin/plugin.json``, ``hooks/cursor.json`` (camelCase events), ``cursor/agents/<role>.md``, ``cursor/commands/probandia-<name>.md``, ``cursor/mcp.json`` |
| Factory Droid | ``.factory-plugin/plugin.json``, ``droids/<role>.md`` |
| Antigravity | the root ``plugin.json`` (shared), ``mcp_config.json`` and ``hooks.json`` at the root |
| Grok Build | nothing: it reads ``.claude-plugin/``, without the MCP server too |
| OpenCode | nothing here: ``install --harness opencode`` |
"""
import json
import os

from probandia.config import registry
from probandia.config.harness import TITLES
from probandia.install import convert

AGENT_PLUGINS_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"
AGENT_PLUGINS_MCP_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json"
GENERATED_NOTE = "Generated by: python run_probandia.py manifests generate"


def _json(obj):
    return json.dumps(obj, ensure_ascii=False, indent=2) + "\n"


def _source(root):
    with open(os.path.join(root, ".claude-plugin", "plugin.json"), encoding="utf-8") as fh:
        return json.load(fh)


def _identity(src):
    out = {k: src[k] for k in ("name", "version", "description") if k in src}
    if "author" in src:
        out["author"] = src["author"]
    for key in ("keywords", "homepage", "repository", "license"):
        if key in src:
            out[key] = src[key]
    return out


def _interface(src):
    return {
        "displayName": "Probandia",
        "shortDescription": src.get("description", ""),
        "developerName": src.get("author", {}).get("name", ""),
        "category": "Productivity",
        "capabilities": [],
    }


# T130, T259: hooks/hooks.json, read by Claude Code, Grok Build and Factory Droid, runs under sh, bash or Git Bash,
# and on Windows under PowerShell (Grok) or cmd (Droid): `python … || python3 …` holds in all of them but Windows
# PowerShell 5.1. python first: python3 can open the Store on Windows; a hook always exits 0, refusals included,
# so the second one runs only when python is missing (Debian, Ubuntu, macOS). A harness that has a Windows
# command of its own takes the first one alone.
FALLBACK = " || python3 "


def windows_command(command):
    return command.split(FALLBACK, 1)[0]


def codex_hooks(claude_hooks):
    """``hooks/codex.json``: the Claude hooks, each with Codex's ``commandWindows``."""
    out = json.loads(json.dumps(claude_hooks))
    for groups in out.get("hooks", {}).values():
        for group in groups:
            for hook in group.get("hooks", []):
                hook["commandWindows"] = windows_command(hook["command"])
    return out


# Codex and Agent Plugins 1.0


def codex_plugin(src):
    """``.codex-plugin/plugin.json``: skills, the portable MCP file, hooks, interface."""
    out = _identity(src)
    out.update({"skills": "./skills/", "mcpServers": "./mcp.json", "hooks": "./hooks/codex.json",
                "interface": _interface(src)})
    return out


def root_plugin(src):
    """The root ``plugin.json``: the Agent Plugins 1.0 core and the Codex block.
    Antigravity reads the same file (it only needs ``name``)."""
    out = {"$schema": AGENT_PLUGINS_SCHEMA}
    out.update(_identity(src))
    out["extensions"] = {"com.openai": {"hooks": "./hooks/codex.json", "interface": _interface(src)}}
    return out


def codex_marketplace(src):
    """``.agents/plugins/marketplace.json``: Codex wants a policy and a category per plugin."""
    return {"name": "probandia", "interface": {"displayName": "Probandia"},
            "plugins": [{"name": src["name"], "source": {"source": "local", "path": "./"},
                         "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                         "category": "Productivity"}]}


def portable_mcp():
    """``mcp.json``: Codex expands ``${PLUGIN_ROOT}`` here, not ``${CLAUDE_PLUGIN_ROOT}``."""
    return {"$schema": AGENT_PLUGINS_MCP_SCHEMA,
            "mcpServers": {"probandia": {"type": "stdio", "command": "python",
                                         "args": ["${PLUGIN_ROOT}/run_probandia.py", "mcp"],
                                         "cwd": "${PLUGIN_ROOT}"}}}


# Cursor

CURSOR_EVENTS = {  # Claude event -> Cursor events
    "PreToolUse": ("beforeShellExecution", "beforeMCPExecution"),
    "PostToolUse": ("afterMCPExecution",),   # hook log has nothing to do after a shell command (G1)
    "Stop": ("stop",),
    # agent-models R6: the session hook keeps the project's copies of the agents (fire-and-forget in Cursor:
    # a copy written then counts from the next session)
    "SessionStart": ("sessionStart",),
}


def cursor_hooks(claude_hooks):
    """``hooks/cursor.json``: the Claude hooks with Cursor's camelCase events."""
    out = {}
    for event, groups in claude_hooks.get("hooks", {}).items():
        for target in CURSOR_EVENTS.get(event, ()):
            for group in groups:
                for hook in group.get("hooks", []):
                    # Cursor's refusals have their own format: the engine must know who calls
                    out.setdefault(target, []).append(
                        {"command": windows_command(hook["command"]) + " --harness cursor", "timeout": hook.get("timeout", 15)})
    return {"version": 1, "hooks": out}


def cursor_variables():
    """Team variables for the eight Essential settings, as a JSON Schema."""
    props = {}
    for s in registry.harness_settings():
        entry = {"type": "number" if s.type == "int" else "string", "title": TITLES[s.key],
                 "default": ",".join(s.default) if s.type == "list" else s.default}
        if s.type == "enum":
            entry["enum"] = list(s.values)
        props[s.harness_key] = entry
    return {"type": "object", "properties": props}


def cursor_mcp():
    """``cursor/mcp.json``: Cursor expands ``${CURSOR_PLUGIN_ROOT}`` there, not ``${PLUGIN_ROOT}``
    (cursor.com/docs/plugins, read 17 Oct. 2026); the harness is named for the log and the quotas."""
    return {"mcpServers": {"probandia": {"command": "python",
                                         "args": ["${CURSOR_PLUGIN_ROOT}/run_probandia.py", "mcp"],
                                         "env": {"PROBANDIA_HARNESS": "cursor"}}}}


def cursor_plugin(src):
    out = _identity(src)
    out.update({"skills": "./skills/", "agents": "./cursor/agents/", "commands": "./cursor/commands/",
                "hooks": "./hooks/cursor.json", "mcpServers": "./cursor/mcp.json",
                "variables": cursor_variables()})
    return out


def claude_agent(role, fm, body):
    """``.claude-plugin/agents/<role>.md`` (version-1.0.0 T267): the header of ``agents/<role>.md`` with the
    role's model and effort, and its tools as Claude Code writes them, ``A, B``."""
    fields = {"name": fm.get("name", role), "description": fm.get("description", ""), "model": fm.get("model"),
              "effort": fm.get("effort")}
    fields.update({k: v for k, v in fm.items() if k not in fields})
    if fields.get("tools"):
        fields["tools"] = ", ".join(convert.tools_list(fields["tools"]))
    return convert.front_matter(fields) + "\n" + body


def cursor_agent(role, fm, body):
    """Cursor sets the effort inside the model value; with the harness's own
    model (``inherit``) no effort can be given."""
    fields = {"name": f"probandia-{role}", "description": fm.get("description", ""),
              "model": "inherit"}
    tools = convert.tools_list(fm.get("tools"))
    if tools:
        fields["tools"] = ", ".join(tools)
    if role == "contradictor":
        fields["permissionMode"] = "readonly"
    return convert.front_matter(fields) + "\n" + body


# Factory Droid

# Claude Code tool -> Factory Droid tool id; None: none in Droid (Skill is always
# there and must not be listed; an unknown id fails the droid's validation)
DROID_TOOLS = {"Bash": "Execute", "Write": "Create", "WebFetch": "FetchUrl", "Skill": None,
               "SendMessage": None, "Agent": None}


def factory_plugin(src):
    return _identity(src)


def droid_agent(role, fm, body):
    fields = {"name": f"probandia-{role}", "description": fm.get("description", ""),
              "model": fm.get("model", "inherit"),
              "reasoningEffort": convert.EFFORT_MAP["droid"][fm.get("effort", "medium")]}
    tools = [DROID_TOOLS.get(t, t) for t in convert.tools_list(fm.get("tools"))]
    # an MCP server pattern (mcp__claude-in-chrome) is not a Droid id: Droid lists exact MCP tool ids
    tools = [t for t in dict.fromkeys(tools) if t and not t.startswith("mcp__")]
    if tools:
        fields["tools"] = tools
    return convert.front_matter(fields) + "\n" + body


# Antigravity

def antigravity_mcp():
    """Antigravity starts plugin MCP servers in the plugin folder."""
    return {"mcpServers": {"probandia": {"command": "python", "args": ["run_probandia.py", "mcp"]}}}


def antigravity_hooks():
    """Antigravity's hooks run in the folder of hooks.json (the plugin root), with
    its own events: no prompt event, no subagent stop."""
    def h(function, timeout):
        return {"type": "command", "command": f"python run_probandia.py hook {function} --harness antigravity",
                "timeout": timeout}
    return {"probandia": {
        "PreToolUse": [{"matcher": ".*", "hooks": [h("guard", 10)]}],
        "PostToolUse": [{"matcher": "search_web|send_message|mcp_.*",
                         "hooks": [h("log", 15)]}],
        "PreInvocation": [h("digest", 15)],
    }}



# the whole set


def targets(root=None):
    """{relative path: expected content} of every generated file."""
    root = root or convert.package_root()
    src = _source(root)
    with open(os.path.join(root, "hooks", "hooks.json"), encoding="utf-8") as fh:
        claude_hooks = json.load(fh)
    out = {
        ".codex-plugin/plugin.json": _json(codex_plugin(src)),
        "plugin.json": _json(root_plugin(src)),
        "mcp.json": _json(portable_mcp()),
        ".agents/plugins/marketplace.json": _json(codex_marketplace(src)),
        ".cursor-plugin/plugin.json": _json(cursor_plugin(src)),
        "hooks/codex.json": _json(codex_hooks(claude_hooks)),
        "hooks/cursor.json": _json(cursor_hooks(claude_hooks)),
        "cursor/mcp.json": _json(cursor_mcp()),
        ".factory-plugin/plugin.json": _json(factory_plugin(src)),
        "mcp_config.json": _json(antigravity_mcp()),
        "hooks.json": _json(antigravity_hooks()),
    }
    for role, (fm, body) in convert.agents(root).items():
        out[f".claude-plugin/agents/{role}.md"] = claude_agent(role, fm, body)
        out[f"cursor/agents/{role}.md"] = cursor_agent(role, fm, body)
        out[f"droids/{role}.md"] = droid_agent(role, fm, body)
    # T263: Cursor names a plugin's command after its file, with no prefix: /status would meet its own and other
    # plugins'. Claude Code and Grok keep commands/ (/probandia:status); Factory Droid reads only commands/.
    folder = os.path.join(root, "commands")
    for name in sorted(os.listdir(folder)):
        if name.endswith(".md"):
            with open(os.path.join(folder, name), encoding="utf-8") as fh:
                text = fh.read()
            # Cursor takes a command's name from its front matter's name (cursor.com/docs/reference/plugins)
            out[f"cursor/commands/probandia-{name}"] = text.replace("---\n", f"---\nname: probandia-{name[:-3]}\n", 1)
    return out


def generate(root=None):
    """Writes every generated file. Returns the paths that changed."""
    from probandia.util.fs import atomic_write_text

    root = root or convert.package_root()
    changed = []
    expected = targets(root)
    for rel, content in expected.items():
        path = os.path.join(root, *rel.split("/"))
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        if current != content:
            atomic_write_text(path, content)
            changed.append(rel)
    for folder in (".claude-plugin/agents", "cursor/agents", "cursor/commands", "droids"):  # agents removed from the source
        full = os.path.join(root, *folder.split("/"))
        if os.path.isdir(full):
            for name in os.listdir(full):
                rel = f"{folder}/{name}"
                if rel not in expected:
                    os.unlink(os.path.join(full, name))
                    changed.append(rel)
    return changed


def check(root=None):
    """The generated files that differ from what ``generate`` would write."""
    root = root or convert.package_root()
    stale = []
    expected = targets(root)
    for rel, content in expected.items():
        path = os.path.join(root, *rel.split("/"))
        try:
            with open(path, encoding="utf-8") as fh:
                if fh.read() != content:
                    stale.append(rel)
        except FileNotFoundError:
            stale.append(rel)
    for folder in (".claude-plugin/agents", "cursor/agents", "cursor/commands", "droids"):
        full = os.path.join(root, *folder.split("/"))
        if os.path.isdir(full):
            stale += [f"{folder}/{n}" for n in os.listdir(full) if f"{folder}/{n}" not in expected]
    return stale
